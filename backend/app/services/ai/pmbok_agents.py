def _slug(s: str) -> str:
    return re.sub(r"\W+", "_", s or "").strip("_").lower() or "item"


def itto_to_structured(kind: str, items: Any) -> List[Dict[str, Any]]:
    """把 inputs/tools/outputs 统一为结构化项。

    统一字段（输入/工具/输出完全一致）：
      key, label, optional, enabled, kind, template_prompt
    - input/output 默认必选(optional=False)、物料类型为 file、启用(enabled=True)
    - tool 默认可选(optional 反映是否必需)、类型为 technique、启用(enabled=True)
    - enabled 表示该项是否被「勾选启用」参与本次运行；与 optional（必需/可选）无关。
    """
    out: List[Dict[str, Any]] = []
    for it in (items or []):
        if isinstance(it, dict):
            d = {
                "key": it.get("key") or _slug(str(it.get("label", ""))),
                "label": it.get("label") or it.get("key") or "",
                "optional": bool(it.get("optional", False)),
                "enabled": bool(it.get("enabled", True)),
                "kind": it.get("kind") or ("file" if kind in ("input", "output") else "technique"),
                "template_prompt": it.get("template_prompt") or "",
            }
        else:
            d = {
                "key": _slug(str(it)),
                "label": str(it),
                "optional": False if kind in ("input", "output") else True,
                "enabled": True,
                "kind": "file" if kind in ("input", "output") else "technique",
                "template_prompt": "",
            }
        out.append(d)
    return out


