async def _collect_context(db, project_id: Optional[str]) -> Dict[str, Any]:
    ctx: Dict[str, Any] = {"has_project": False}
    if not project_id:
        return ctx
    proj = await db.get(Project, project_id)
    if not proj:
        return ctx
    ctx["has_project"] = True
    ctx["project"] = {
        "name": proj.name,
        "industry_type": getattr(proj, "industry_type", None),
        "project_type": getattr(proj, "project_type", None),
        "start_date": str(getattr(proj, "start_date", "") or ""),
        "end_date": str(getattr(proj, "end_date", "") or ""),
        "budget": getattr(proj, "budget", None),
    }
    total = (await db.execute(
        select(func.count(Task.id)).where(Task.project_id == project_id, Task.is_deleted.is_(False))
    )).scalar() or 0
    done = (await db.execute(
        select(func.count(Task.id)).where(
            Task.project_id == project_id, Task.is_deleted.is_(False),
            Task.status == TaskStatus.DONE.value)
    )).scalar() or 0
    risks = (await db.execute(
        select(func.count(Risk.id)).where(Risk.project_id == project_id)
    )).scalar() or 0
    ctx["tasks_total"] = total
    ctx["tasks_done"] = done
    ctx["risks_total"] = risks
    return ctx


